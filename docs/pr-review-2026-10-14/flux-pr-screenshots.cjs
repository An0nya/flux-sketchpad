const fs = require('fs');
const path = require('path');
const pw = require('/Users/anya/Projects/agent-qa/node_modules/playwright');
const out = '/Users/anya/Projects/flux-sketchpad/docs/pr-review-2026-10-14';
module.exports = async function () {
  fs.mkdirSync(out, { recursive: true });
  const browser = await pw.chromium.launch({ channel: 'chromium', args: ['--enable-unsafe-webgpu'] });
  const errors = [], evidence = {};
  async function open() {
    const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
    page.on('pageerror', e => errors.push(String(e)));
    page.on('console', m => { if (m.type() === 'error' && !/404/.test(m.text())) errors.push(m.text()); });
    await page.goto('http://localhost:8836/index.html');
    await page.waitForFunction(() => window.RF && RF.UI && RF.UI.store && RF.SolverHost && !RF.SolverHost.loading(), null, { timeout: 60000 });
    await page.waitForFunction(() => !RF.UI.solving && !RF.UI.pendingA, null, { timeout: 180000 });
    return page;
  }
  try {
    const p = await open();
    await p.locator('.pane-head [data-mode="D"]').click();
    await p.waitForFunction(() => { const u = RF.UI; return u.store.scene.mode === 'D' && !u.solving && u.run && u.run.ctx.done && u.spec && u.spec.ctx === u.run.ctx && u.spec.full && u.spec.ev; }, null, { timeout: 180000 });
    await p.locator('[data-disp="drive"]').click();
    await p.waitForTimeout(1200);
    await p.locator('[data-anim="animate"]').click();
    await p.waitForTimeout(2500);
    const a = await p.evaluate(() => ({ frames: RF.DriveAnim.stats().frames, dist: RF.UI.dvAnim.dist }));
    await p.waitForTimeout(1200);
    const b = await p.evaluate(() => ({ frames: RF.DriveAnim.stats().frames, dist: RF.UI.dvAnim.dist }));
    if (!(b.frames > a.frames && b.dist > a.dist)) throw new Error('Screenshot run: animation did not advance');
    await p.screenshot({ path: path.join(out, 'drive-animation-pane.png') });
    await p.locator('[data-anim="popout"]').click();
    await p.waitForTimeout(2500);
    await p.screenshot({ path: path.join(out, 'drive-animation-large.png') });
    evidence.drive = { before: a, after: b, stats: await p.evaluate(() => RF.DriveAnim.stats()), gpu: await p.evaluate(() => RF.GPUTrace ? RF.GPUTrace.pref() : null) };
    await p.locator('[data-anim="play"]').click();
    await p.waitForTimeout(400);
    const f = await p.evaluate(() => RF.DriveAnim.stats().frames);
    await p.waitForTimeout(500);
    evidence.drive.paused = f === await p.evaluate(() => RF.DriveAnim.stats().frames);
    await p.close();
    const q = await open();
    await q.locator('.pane-head [data-mode="C"]').click();
    await q.waitForTimeout(500);
    await q.waitForFunction(() => !RF.UI.solving && !RF.UI.pendingA, null, { timeout: 120000 });
    await q.evaluate(() => { RF.Controller.actions.setProfile(RF.UI.store, []); RF.UI.afterChange(); });
    await q.waitForTimeout(700);
    const point = async (r,z) => q.evaluate(([r,z]) => { const cv=document.getElementById('left-canvas'), box=cv.getBoundingClientRect(), p=RF.UI.vProf.toScreen(r,z); return [box.left+p[0],box.top+p[1]]; }, [r,z]);
    const click = async (r,z) => { const p=await point(r,z); await q.mouse.click(...p); await q.waitForTimeout(700); };
    await click(2,-12); await click(20,10);
    const mid = await q.evaluate(() => { const cv=RF.UI.curveNow(); return RF.Profile.segGeom(cv.nodes[0],cv.nodes[1],cv.bulge[0]).mid; });
    const start=await point(...mid), end=await point(mid[0]+4,mid[1]-3);
    await q.mouse.move(...start); await q.mouse.down(); await q.mouse.move(...end,{steps:12}); await q.mouse.up(); await q.waitForTimeout(900);
    await click(12,23);
    evidence.profile = await q.evaluate(() => ({ curve: RF.UI.store.scene.modeC.curve, flattenedPoints: RF.UI.store.scene.modeC.profile.length, surfaces: RF.Profile.build(RF.UI.store.scene).surfaces.length, live: !!RF.Profile.curveLive(RF.UI.store.scene.modeC) }));
    if (!evidence.profile.live || evidence.profile.flattenedPoints <= 3) throw new Error('Screenshot run: real pointer edit did not create a live bent curve');
    await q.screenshot({ path: path.join(out, 'profile-curve-editor.png') });
    await q.locator('[data-expand="editor"]').click(); await q.waitForTimeout(700);
    await q.screenshot({ path: path.join(out, 'profile-curve-editor-large.png') });
    const saved = await q.evaluate(() => RF.State.serialize(RF.UI.store.scene));
    await q.reload();
    await q.waitForFunction(() => window.RF && RF.UI && RF.UI.store && RF.SolverHost && !RF.SolverHost.loading(), null, { timeout: 60000 });
    await q.waitForTimeout(700);
    evidence.profile.reload = await q.evaluate((saved) => { const a=RF.State.deserialize(saved).modeC, b=RF.UI.store.scene.modeC; return { expectedCurve: a.curve, actualCurve: b.curve, expectedPoints: a.profile.length, actualPoints: b.profile.length, mode: RF.UI.store.scene.mode, preserved: JSON.stringify(a.curve)===JSON.stringify(b.curve) && JSON.stringify(a.profile)===JSON.stringify(b.profile) && !!RF.Profile.curveLive(b) }; },saved);
    evidence.profile.reloadPreserved = evidence.profile.reload.preserved;
    await q.close();
    evidence.errors=errors;
    fs.writeFileSync(path.join(out,'screenshot-evidence.json'),JSON.stringify(evidence,null,2));
    for (const file of ['flux-f2-review.log','flux-f4-review.log','flux-f2-all.log','flux-f4-all.log']) fs.copyFileSync('/private/tmp/'+file,path.join(out,file));
    console.log(JSON.stringify(evidence,null,2));
    if (errors.length || !evidence.drive.paused || !evidence.profile.reloadPreserved) process.exitCode=1;
  } finally { await browser.close(); }
};
